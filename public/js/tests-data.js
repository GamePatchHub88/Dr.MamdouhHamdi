  /* ans: مصفوفة قيم 0..4 بنفس ترتيب البنود. تُعيد {score,max,pct,band,level} */
  function score(t, ans) {
    var s = 0;
    for (var i = 0; i < t.q.length; i++) {
      var v = +(ans && ans[i]);
      if (!(v >= 0 && v <= 4)) v = 0;
      if (t.q[i].r) v = 4 - v;
      s += v;
    }
    var max = t.q.length * 4, pct = Math.round(s / max * 100), b = t.bands[t.bands.length - 1];
    for (var j = 0; j < t.bands.length; j++) if (pct <= t.bands[j].max) { b = t.bands[j]; break; }
    /* بند حرج (أفكار إيذاء النفس): أي إجابة غير «أبداً» تُفعّل تنبيه أمان */
    var flag = false;
    for (var k = 0; k < t.q.length; k++) if (t.q[k].crit && +(ans && ans[k]) > 0) flag = true;
    return { score: s, max: max, pct: pct, band: b, level: b.k, flag: flag };
  }

  /* تفصيل: أعلى 3 بنود أثّرت في الدرجة (للبنود غير العكسية تُعاد قيمتها، وللعكسية 4-قيمة) */
  function top(t, ans, n) {
    var arr = [];
    for (var i = 0; i < t.q.length; i++) {
      var v = +(ans && ans[i]); if (!(v >= 0 && v <= 4)) v = 0;
      if (t.q[i].r) v = 4 - v;
      arr.push({ i: i, text: t.q[i].t, r: !!t.q[i].r, v: v });
    }
    arr.sort(function (a, b) { return b.v - a.v; });
    return arr.filter(function (x) { return x.v >= 3; }).slice(0, n || 3);
  }

